"""Audit the built seven-codec image: no legacy backend or silent fallback."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('build',type=Path,nargs='?',default=ROOT/'software/build');a=p.parse_args()
commands=json.loads((a.build/'compile_commands.json').read_text(encoding='utf-8'))
paths=[str(c['file']).replace('\\','/') for c in commands]
for old in ('chime_freeaptx/freeaptx.c','espressif__esp_audio_codec','vendor/native_bt/','vendor/esp-idf/'):
    assert not any(old in path for path in paths),'Legacy source still compiled: '+old
port=a.build/'esp-idf/chime_codec_reference/s31-port'
pins=json.loads((ROOT/'software/components/chime_codec_reference/UPSTREAM.json').read_text())
receipt=json.loads((port/'CHIME_PORT.json').read_text())
assert receipt['commit']==pins['commit'] and receipt['repository']==pins['repository']
for name,digest in receipt['files'].items():assert hashlib.sha256((port/name).read_bytes()).hexdigest()==digest
required=['sbc/decoder/srce/decoder-sbc.c','libaac-lc/libhelix_aac/aacdec.c','libfreeaptx/main/freeaptx.c','opus/src/opus_decoder.c','libldac-dec/src/ldacBT.c','lhdc-v5/lhdc_dec.c']
for source in required:assert any('/s31-port/external/'+source in path for path in paths),'Backend missing: '+source
mapping=(a.build/'audio_dsp_firmware.map').read_text(encoding='utf-8')
assert 'esp-idf/chime_freeaptx/libchime_freeaptx.a(' not in mapping
assert 'espressif__esp_audio_codec' not in mapping
for symbol in ('OI_CODEC_SBC_DecodeFrame','AACDecode','aptx_init','opus_decoder_create','ldacBT_decode','lhdc_dec_decode_frame'):
    assert symbol in mapping,'Decoder not linked: '+symbol
print('PASS built seven-codec S31 image: pinned generated bytes; six library families for seven codecs; no old esp_audio_codec/freeaptx/native_bt sources or archive members')

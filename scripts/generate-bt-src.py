"""Generate original Kaiser-windowed fractional-delay FIR coefficients (Q2.30).
No runtime allocation/trigonometry. 192 taps, 256 phases + interpolation endpoint.
Run from any cwd. --check verifies committed coefficients exactly.
"""
from pathlib import Path
import math,sys
N=192
P=256
def i0(x):
    result=term=1.0
    for k in range(1,100):
        term*=x*x/(4*k*k);result+=term
        if term<result*1e-17:break
    return result
lines=['/* Generated by scripts/generate-bt-src.py; do not edit. */',
       '#define CHIME_SRC_TAPS 192U', '#define CHIME_SRC_PHASES 256U',
       'static const int32_t src_coeff[3][257][192]={']
for cutoff in (0.45,21025/44100,22000/48000):
    lines.append('{')
    for phase in range(P+1):
        frac=phase/P
        values=[]
        for k in range(N):
            t=k-(N-1)/2-frac
            z=t/((N+1)/2)
            w=i0(10.1*math.sqrt(max(0,1-z*z)))/i0(10.1) if abs(z)<=1 else 0
            values.append((2*cutoff if t==0 else math.sin(2*math.pi*cutoff*t)/(math.pi*t))*w)
        total=sum(values);q=[round(x/total*(1<<30)) for x in values]
        q[N//2]+= (1<<30)-sum(q)
        assert all(abs(x)<=(1<<30) for x in q), 'SIMD signed-half coefficient bound'
        assert sum(abs(x) for x in q)<3*(1<<30), 'unexpected FIR coefficient L1 bound'
        lines.append('{'+','.join(map(str,q))+'},')
    lines.append('},')
lines.append('};')
text='\n'.join(lines)+'\n'
path=Path(__file__).resolve().parents[1]/'software/main/chime_bt_src_coeff.h'
if '--check' in sys.argv:
    assert path.read_text(encoding='utf-8')==text,'stale SRC coefficients'
else:path.write_text(text,encoding='utf-8')
print('PASS SRC coefficients: 192 taps, 256 phases, exact DC, L1 < 3, three rate banks')

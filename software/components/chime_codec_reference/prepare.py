"""Verify upstream bytes, run the upstream ports, select codec-only lifecycle.
No host/transport/worker from the upstream project is linked into Chime.
"""
import hashlib,json,importlib.util,argparse,sys
sys.dont_write_bytecode=True
from pathlib import Path

def load(path,name):
    spec=importlib.util.spec_from_file_location(name,path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module

def without_validator(text,name):
    start=text.index("uint8_t "+name+"(")
    body=text.index("{",start);depth=1;end=body+1
    while depth:
        depth+=(text[end]=="{")-(text[end]=="}");end+=1
    return text[:start]+"/* Chime retains its own pinned AVDTP capability validation. */\n"+text[end:]

def instrument_lhdc(output,text):
    # Diagnostics only, not changes to codec arithmetic/return values. Preserve
    # vendor files; every generated byte is recorded in CHIME_PORT.json.
    text='#include "chime_reference_diagnostics.h"\n'+text
    start=text.index("static dbt_result_t open_decoder(")
    end=text.index("static dbt_result_t batch_finish(",start)
    body=text[start:end]
    sites=[
        ("return DBT_INVALID;","configuration"),
        ("return DBT_BUSY;","singleton"),
        ("return DBT_INVALID;","workspace-size"),
        ("return DBT_NO_SPACE;","state-allocation"),
        ("return DBT_NO_SPACE;","decoder-init-or-entropy"),
        ("return DBT_INVALID;","pcm-scratch")]
    import re
    found=list(re.finditer(r"return (DBT_INVALID|DBT_BUSY|DBT_NO_SPACE);",body))
    if len(found)!=len(sites):raise RuntimeError("LHDC open diagnostic sites moved")
    for match,(expected,stage) in reversed(list(zip(found,sites))):
        if match.group()!=expected:raise RuntimeError("LHDC open diagnostic return changed")
        body=body[:match.start()]+'{chime_reference_init_failed("lhdc-'+stage+'",'+match.group(1)+');'+expected+'}'+body[match.end():]
    text=text[:start]+body+text[end:]
    dec=output/"lhdc/lhdc_dec.c"
    source=dec.read_text(encoding="utf-8")
    start=source.index("lhdc_decoder_t *lhdc_dec_init(")
    end=source.index("dec->initialized = 1;",start)
    init=source[start:end]
    # The five NULL returns are workspace, buffers, IMDCT, window and entropy.
    if init.count("return NULL;")!=5:raise RuntimeError("LHDC init diagnostic sites moved")
    for stage in ("workspace","buffers","imdct","window","entropy"):
        init=init.replace("return NULL;",'chime_reference_init_failed("lhdc-'+stage+'",-1); return /* diagnosed */ NULL;',1)
    source='#include "chime_reference_diagnostics.h"\n'+source[:start]+init+source[end:]
    dec.write_text(source,encoding="utf-8")
    return text

def generate(output):
    root=Path(__file__).resolve().parent;v=root/"vendor"
    pins=json.loads((root/"UPSTREAM.json").read_text(encoding="utf-8"))
    for name,digest in pins["files"].items():
        if hashlib.sha256((v/name).read_bytes()).hexdigest()!=digest:
            raise RuntimeError("Upstream codec source changed: "+name)
    output.mkdir(parents=True,exist_ok=True)
    native=v/"native_bt/codecs"
    ldac=v/"esp-idf/components/bt/host/bluedroid/external/libldac-dec/src"
    load(native/"ldac/prepare_port.py","ldac_port").generate(ldac,output/"ldac")
    load(native/"lhdcv5/prepare_port.py","lhdc_port").generate(native/"lhdcv5/source_snapshot/decoder",output/"lhdc")
    # Upstream narrows scale factors to int8_t, but only checked the upper
    # bound. ASan malformed-frame replay exposed ga_sf[-1] after wraparound.
    # Reject the negative index before word-length reconstruction/dequant;
    # valid bitstreams and the upstream codec arithmetic are unchanged.
    unpack=output/"ldac/unpack_ldac.o.c"
    text=unpack.read_text(encoding="utf-8")
    old="if (p_ac->a_idsf[iqu] > 31) {"
    if text.count(old)!=1:raise RuntimeError("LDAC scale-index guard moved")
    unpack.write_text(text.replace(old,"if (p_ac->a_idsf[iqu] < 0 || p_ac->a_idsf[iqu] > 31) {"),encoding="utf-8")

    # Lifecycle/allocation functions only; keep Chime's existing decoder task.
    common=(native/"common/dbt_codec.c").read_text(encoding="utf-8")
    common=common[:common.index("static bool enabled(")]
    (output/"dbt_codec_lifecycle.c").write_text(common,encoding="utf-8")
    (output/"dbt_ldac.c").write_text(without_validator((native/"ldac/dbt_ldac.c").read_text(encoding="utf-8"),"dbt_a2dp_ldac_validate"),encoding="utf-8")
    (output/"dbt_lhdcv5_codec.c").write_text(instrument_lhdc(output,without_validator((native/"lhdcv5/dbt_lhdcv5_codec.c").read_text(encoding="utf-8"),"dbt_a2dp_lhdcv5_validate")),encoding="utf-8")
    generated={p.relative_to(output).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(output.rglob("*")) if p.is_file() and p.name!="CHIME_PORT.json"}
    (output/"CHIME_PORT.json").write_text(json.dumps({"commit":pins["commit"],"files":generated},indent=2)+"\n",encoding="utf-8")
    return pins["commit"]

if __name__=="__main__":
    parser=argparse.ArgumentParser();parser.add_argument("--output",type=Path,required=True)
    print(generate(parser.parse_args().output))
